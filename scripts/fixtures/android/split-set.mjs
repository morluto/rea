// Build the synthetic Android split-set fixtures from the tracked manifest
// sources with a caller-supplied aapt2. Nothing is downloaded or installed.
//
//   node scripts/fixtures/android/split-set.mjs \
//     --aapt2 /abs/path/aapt2 --android-jar /abs/path/android.jar --out DIR \
//     [--emit-golden src/artifacts/android/AndroidSplitSetApks.fixture.ts]
//
// Requirements: an aapt2 and an android.jar from the Android SDK
// (build-tools and platforms), and the `zip` executable on PATH, which adds
// the placeholder native library to the ABI split.
import { execFileSync } from "node:child_process";
import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  rmSync,
  utimesSync,
  writeFileSync,
} from "node:fs";
import { dirname, join, resolve } from "node:path";
import { tmpdir } from "node:os";
import { fileURLToPath } from "node:url";

const args = new Map();
for (let i = 2; i < process.argv.length; i += 2)
  args.set(process.argv[i], process.argv[i + 1]);
const need = (flag) => {
  const value = args.get(flag);
  if (value === undefined) throw new Error(`Missing ${flag}`);
  return resolve(value);
};
const aapt2 = need("--aapt2");
const androidJar = need("--android-jar");
const out = need("--out");

const fail = (message) => {
  process.stderr.write(`split-set fixtures: ${message}\n`);
  process.exit(1);
};
if (!existsSync(aapt2)) fail(`aapt2 not found at ${aapt2}`);
if (!existsSync(androidJar)) fail(`android.jar not found at ${androidJar}`);
try {
  execFileSync("zip", ["-v"], { stdio: "ignore" });
} catch {
  fail(
    "the `zip` executable is required on PATH to add the placeholder native library",
  );
}
const sources = join(dirname(fileURLToPath(import.meta.url)), "split-set");
mkdirSync(out, { recursive: true });

const built = [];
for (const file of readdirSync(sources)
  .filter((n) => n.endsWith(".xml"))
  .sort()) {
  const name = file.replace(/\.xml$/u, "");
  const apk = join(out, `${name}.apk`);
  execFileSync(
    aapt2,
    ["link", "--manifest", join(sources, file), "-I", androidJar, "-o", apk],
    { stdio: "pipe" },
  );
  built.push({ name, apk });
}
// Add a placeholder native payload (not an ELF) so ABI evidence is path-level only.
const arm = built.find((b) => b.name === "config-arm64_v8a");
const stage = mkdtempSync(join(tmpdir(), "rea-split-"));
try {
  mkdirSync(join(stage, "lib/arm64-v8a"), { recursive: true });
  writeFileSync(
    join(stage, "lib/arm64-v8a/libfoo.so"),
    "not an ELF; ABI evidence is path-level only\n",
  );
  // Fixed timestamps and no extra attributes keep the archive reproducible.
  const fixed = new Date("1980-01-01T00:00:00Z");
  for (const path of ["lib", "lib/arm64-v8a", "lib/arm64-v8a/libfoo.so"])
    utimesSync(join(stage, path), fixed, fixed);
  execFileSync("zip", ["-q", "-X", "-D", "-r", arm.apk, "lib"], { cwd: stage });
} finally {
  rmSync(stage, { recursive: true, force: true });
}

const emit = args.get("--emit-golden");
if (emit !== undefined) {
  const lines = [
    "// Generated by scripts/fixtures/android/split-set.mjs from tracked sources.",
    `// aapt2: ${execFileSync(aapt2, ["version"]).toString().trim()}`,
    "// Whole APKs (base64). Regenerate with --emit-golden; do not edit by hand.",
    "export const SPLIT_SET_APKS = {",
  ];
  for (const { name, apk } of built)
    lines.push(
      `  ${JSON.stringify(name)}: ${JSON.stringify(readFileSync(apk).toString("base64"))},`,
    );
  lines.push("} as const;", "");
  writeFileSync(resolve(emit), lines.join("\n"));
}
process.stdout.write(`${built.map((b) => b.apk).join("\n")}\n`);
