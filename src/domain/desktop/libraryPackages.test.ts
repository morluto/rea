import { describe, expect, it } from "vitest";

import { err, ok } from "../result.js";
import type { ElfDependencies } from "./elfDependencies.js";
import {
  installableLibraryPackages,
  libraryClosure,
  libraryPackageNames,
  parseLinkerCache,
} from "./libraryPackages.js";

/** `ldconfig -p` lines from Ubuntu 24.04 arm64, plus an amd64 libc as a multiarch host lists it. */
const LINKER_CACHE = [
  "427 libs found in cache `/etc/ld.so.cache'",
  "\tlibnss3.so (libc6,AArch64) => /lib/aarch64-linux-gnu/libnss3.so",
  "\tlibnspr4.so (libc6,AArch64) => /lib/aarch64-linux-gnu/libnspr4.so",
  "\tlibc.so.6 (libc6,x86-64, OS ABI: Linux 3.2.0) => /lib/x86_64-linux-gnu/libc.so.6",
  "\tlibc.so.6 (libc6,AArch64) => /lib/aarch64-linux-gnu/libc.so.6",
  "\tld-linux-aarch64.so.1 (libc6,AArch64) => /lib/ld-linux-aarch64.so.1",
  "Cache generated by: ldconfig (Ubuntu GLIBC 2.39-0ubuntu8.6) stable release version 2.39",
].join("\n");

const elf = (
  needed: readonly string[],
  rpath: readonly string[] = [],
  runpath?: readonly string[],
): ElfDependencies => ({
  machine: 183,
  bits: 64,
  needed,
  runpath,
  rpath: runpath === undefined ? rpath : [],
});

const TYPORA = "/usr/share/typora/Typora";

/** Typora's start: libffmpeg.so from its own folder through RPATH $ORIGIN, the rest from the cache. */
const host = (images: Readonly<Record<string, ElfDependencies | string>>) => ({
  dependencies: async (path: string) => {
    const image = images[path];
    return typeof image === "object" ? ok(image) : err(image ?? "missing");
  },
  isFile: async (path: string) => path in images,
});

const typora = {
  path: TYPORA,
  dependencies: elf(
    [
      "libffmpeg.so",
      "libnss3.so",
      "libc.so.6",
      "ld-linux-aarch64.so.1",
      "libsecret-1.so.0",
    ],
    ["$ORIGIN"],
  ),
};

describe("parseLinkerCache", () => {
  it("reads each soname's flags and path", () => {
    expect(parseLinkerCache(LINKER_CACHE)).toContainEqual({
      soname: "libc.so.6",
      flags: ["libc6", "x86-64", "OS ABI: Linux 3.2.0"],
      path: "/lib/x86_64-linux-gnu/libc.so.6",
    });
    expect(parseLinkerCache(LINKER_CACHE)).toHaveLength(5);
  });
});

describe("libraryClosure", () => {
  it("walks DT_NEEDED through RPATH and the cache for the executable's machine", async () => {
    const closure = await libraryClosure(
      typora,
      parseLinkerCache(LINKER_CACHE),
      host({
        "/usr/share/typora/libffmpeg.so": elf(["libc.so.6"], ["$ORIGIN"]),
        "/lib/aarch64-linux-gnu/libnss3.so": elf(["libnspr4.so", "libc.so.6"]),
        "/lib/aarch64-linux-gnu/libnspr4.so": elf(["libc.so.6"]),
        "/lib/aarch64-linux-gnu/libc.so.6": elf(["ld-linux-aarch64.so.1"]),
        "/lib/ld-linux-aarch64.so.1": elf([]),
      }),
      100,
    );

    expect(closure).toEqual({
      libraries: [
        { soname: "libnss3.so", path: "/lib/aarch64-linux-gnu/libnss3.so" },
        { soname: "libc.so.6", path: "/lib/aarch64-linux-gnu/libc.so.6" },
        { soname: "ld-linux-aarch64.so.1", path: "/lib/ld-linux-aarch64.so.1" },
        { soname: "libnspr4.so", path: "/lib/aarch64-linux-gnu/libnspr4.so" },
      ],
      missing: ["libsecret-1.so.0"],
      unreadable: [],
      truncated: false,
    });
  });

  it("stops at its limit and keeps libraries whose dependencies could not be read", async () => {
    const closure = await libraryClosure(
      typora,
      parseLinkerCache(LINKER_CACHE),
      host({
        "/usr/share/typora/libffmpeg.so": elf([]),
        "/lib/aarch64-linux-gnu/libnss3.so": "the file could not be read",
      }),
      2,
    );

    expect(closure).toMatchObject({
      libraries: [{ soname: "libnss3.so" }],
      unreadable: [
        {
          path: "/lib/aarch64-linux-gnu/libnss3.so",
          reason: "the file could not be read",
        },
      ],
      truncated: true,
    });
  });
});

describe("libraryClosure search paths", () => {
  const app = (dependencies: ElfDependencies) => ({
    path: "/opt/app/bin/app",
    dependencies,
  });

  it("normalizes $ORIGIN/.. before telling the app's own folder from system libraries", async () => {
    const closure = await libraryClosure(
      {
        path: "/usr/bin/tool",
        dependencies: elf(["libtool.so.1"], ["$ORIGIN/../lib"]),
      },
      [],
      host({ "/usr/lib/libtool.so.1": elf([]) }),
      10,
    );

    expect(closure.libraries).toEqual([
      { soname: "libtool.so.1", path: "/usr/lib/libtool.so.1" },
    ]);
  });

  it("searches the executable's RPATH for its libraries' own needs unless they have a RUNPATH", async () => {
    const images = {
      "/opt/app/lib/libcore.so": elf(["libhelper.so"]),
      "/opt/app/lib/libhelper.so": elf([]),
    };
    const inherited = await libraryClosure(
      app(elf(["libcore.so"], ["$ORIGIN/../lib"])),
      [],
      host(images),
      10,
    );
    const ownRunpath = await libraryClosure(
      app(elf(["libcore.so"], ["$ORIGIN/../lib"])),
      [],
      host({
        ...images,
        "/opt/app/lib/libcore.so": elf(["libhelper.so"], [], ["/nowhere"]),
      }),
      10,
    );
    const runpathOnly = await libraryClosure(
      app(elf(["libcore.so"], [], ["$ORIGIN/../lib"])),
      [],
      host(images),
      10,
    );

    expect(inherited).toMatchObject({
      libraries: [
        { soname: "libcore.so", path: "/opt/app/lib/libcore.so" },
        { soname: "libhelper.so", path: "/opt/app/lib/libhelper.so" },
      ],
      missing: [],
    });
    expect(ownRunpath.missing).toEqual(["libhelper.so"]);
    expect(runpathOnly.missing).toEqual(["libhelper.so"]);
  });
});

describe("installableLibraryPackages", () => {
  const NOBLE =
    "http://ports.ubuntu.com/ubuntu-ports noble/main arm64 Packages";
  const PPA =
    "https://ppa.launchpadcontent.net/a/b/ubuntu noble/main arm64 Packages";
  const TYPORA = "https://downloads.typora.io/linux ./ Packages";

  it("keeps packages the Ubuntu 24.04 archive or a declared repository offers", () => {
    expect(
      installableLibraryPackages(
        ["libnss3", "libfoo", "typora-helper", "libgone"],
        {
          sources: new Map([
            ["libnss3", [PPA, NOBLE]],
            ["libfoo", [PPA]],
            ["typora-helper", [TYPORA]],
          ]),
          origins: new Map([
            [NOBLE, "Ubuntu"],
            [PPA, "LP-PPA-a-b"],
            [TYPORA, "typora.io"],
          ]),
          declared: new Set([TYPORA]),
        },
      ),
    ).toEqual({
      installable: ["libnss3", "typora-helper"],
      uninstallable: ["libfoo", "libgone"],
    });
  });
});

describe("libraryPackageNames", () => {
  it("drops architecture qualifiers and the application's own package", () => {
    expect(
      libraryPackageNames(
        ["libnss3:arm64", "libc6:arm64", "libnss3:arm64", "typora", "libnspr4"],
        "typora:arm64",
      ),
    ).toEqual(["libc6", "libnspr4", "libnss3"]);
  });
});
