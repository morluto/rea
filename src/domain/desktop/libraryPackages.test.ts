import { describe, expect, it } from "vitest";

import { err, ok } from "../result.js";
import {
  elfLibraryIdentityMatches,
  type ElfLibraryIdentity,
  type ElfDependencies,
} from "./elfDependencies.js";
import {
  installableLibraryPackages,
  libraryClosure,
  libraryPackageNames,
  parseLinkerCache,
} from "./libraryPackages.js";

/** `ldconfig -p` lines from Ubuntu 24.04 arm64, plus an amd64 libc as a multiarch host lists it. */
const LINKER_CACHE = [
  "427 libs found in cache `/etc/ld.so.cache'",
  "\tlibnss3.so (libc6,AArch64) => /lib/aarch64-linux-gnu/libnss3.so",
  "\tlibnspr4.so (libc6,AArch64) => /lib/aarch64-linux-gnu/libnspr4.so",
  "\tlibc.so.6 (libc6,x86-64, OS ABI: Linux 3.2.0) => /lib/x86_64-linux-gnu/libc.so.6",
  "\tlibc.so.6 (libc6,AArch64) => /lib/aarch64-linux-gnu/libc.so.6",
  "\tld-linux-aarch64.so.1 (libc6,AArch64) => /lib/ld-linux-aarch64.so.1",
  "Cache generated by: ldconfig (Ubuntu GLIBC 2.39-0ubuntu8.6) stable release version 2.39",
].join("\n");

const elf = (
  needed: readonly string[],
  rpath: readonly string[] = [],
  runpath?: readonly string[],
): ElfDependencies => ({
  machine: 183,
  bits: 64,
  byte_order: "little",
  needed,
  runpath,
  rpath: runpath === undefined ? rpath : [],
});

const TYPORA = "/usr/share/typora/Typora";
const app = (dependencies: ElfDependencies) => ({
  path: "/opt/app/bin/app",
  dependencies,
});

/** Typora's start: libffmpeg.so from its own folder through RPATH $ORIGIN, the rest from the cache. */
const host = (
  images: Readonly<
    Record<
      string,
      | ElfDependencies
      | { identity: ElfLibraryIdentity | null; reason: string }
      | string
    >
  >,
) => ({
  dependencies: async (path: string, expected: ElfLibraryIdentity) => {
    const image = images[path];
    if (typeof image !== "object")
      return err({
        kind: "unreadable" as const,
        identity: null,
        reason: image ?? "missing",
      });
    const identity = "reason" in image ? image.identity : image;
    if (identity !== null && !elfLibraryIdentityMatches(expected, identity))
      return err({
        kind: "incompatible" as const,
        identity,
        reason: "incompatible ELF",
      });
    return "reason" in image
      ? err({ kind: "unreadable" as const, ...image })
      : ok(image);
  },
  isFile: async (path: string) => path in images,
});

const typora = {
  path: TYPORA,
  dependencies: elf(
    [
      "libffmpeg.so",
      "libnss3.so",
      "libc.so.6",
      "ld-linux-aarch64.so.1",
      "libsecret-1.so.0",
    ],
    ["$ORIGIN"],
  ),
};

describe("parseLinkerCache", () => {
  it("reads each soname's flags and path", () => {
    expect(parseLinkerCache(LINKER_CACHE)).toContainEqual({
      soname: "libc.so.6",
      flags: ["libc6", "x86-64", "OS ABI: Linux 3.2.0"],
      path: "/lib/x86_64-linux-gnu/libc.so.6",
    });
    expect(parseLinkerCache(LINKER_CACHE)).toHaveLength(5);
  });
});

describe("libraryClosure", () => {
  it("walks DT_NEEDED through RPATH and the cache for the executable's machine", async () => {
    const closure = await libraryClosure(
      typora,
      parseLinkerCache(LINKER_CACHE),
      host({
        "/usr/share/typora/libffmpeg.so": elf(["libc.so.6"], ["$ORIGIN"]),
        "/lib/aarch64-linux-gnu/libnss3.so": elf(["libnspr4.so", "libc.so.6"]),
        "/lib/aarch64-linux-gnu/libnspr4.so": elf(["libc.so.6"]),
        "/lib/aarch64-linux-gnu/libc.so.6": elf(["ld-linux-aarch64.so.1"]),
        "/lib/ld-linux-aarch64.so.1": elf([]),
      }),
      100,
    );

    expect(closure).toEqual({
      libraries: [
        { soname: "libnss3.so", path: "/lib/aarch64-linux-gnu/libnss3.so" },
        { soname: "libc.so.6", path: "/lib/aarch64-linux-gnu/libc.so.6" },
        { soname: "ld-linux-aarch64.so.1", path: "/lib/ld-linux-aarch64.so.1" },
        { soname: "libnspr4.so", path: "/lib/aarch64-linux-gnu/libnspr4.so" },
      ],
      missing: ["libsecret-1.so.0"],
      unreadable: [],
      truncated: false,
    });
  });

  it("stops at its limit and keeps libraries whose dependencies could not be read", async () => {
    const closure = await libraryClosure(
      typora,
      parseLinkerCache(LINKER_CACHE),
      host({
        "/usr/share/typora/libffmpeg.so": elf([]),
        "/lib/aarch64-linux-gnu/libnss3.so": {
          identity: elf([]),
          reason: "the file could not be read",
        },
      }),
      2,
    );

    expect(closure).toMatchObject({
      libraries: [{ soname: "libnss3.so" }],
      unreadable: [
        {
          path: "/lib/aarch64-linux-gnu/libnss3.so",
          reason: "the file could not be read",
        },
      ],
      truncated: true,
    });
  });
});

describe("libraryClosure candidate identity", () => {
  it.each([
    { machine: 62, bits: 64 as const },
    { machine: 183, bits: 32 as const },
    { machine: 183, bits: 64 as const, byte_order: "big" as const },
  ])(
    "skips an incompatible search-path candidate ($machine / $bits) before selecting its owner or walking its dependencies",
    async (identity) => {
      const closure = await libraryClosure(
        app(elf(["libcore.so"], [], ["/foreign", "/native"])),
        [],
        host({
          "/foreign/libcore.so": { ...elf(["libdecoy.so"]), ...identity },
          "/native/libcore.so": elf(["libhelper.so"], [], ["/native"]),
          "/native/libhelper.so": elf([]),
        }),
        10,
      );
      expect(closure).toEqual({
        libraries: [
          { soname: "libcore.so", path: "/native/libcore.so" },
          { soname: "libhelper.so", path: "/native/libhelper.so" },
        ],
        missing: [],
        unreadable: [],
        truncated: false,
      });
    },
  );

  it("uses the cache after an incompatible candidate even when its dependency table is unreadable", async () => {
    const closure = await libraryClosure(
      app(elf(["libcore.so"], ["/foreign"])),
      [
        {
          soname: "libcore.so",
          path: "/cached/libcore.so",
          flags: ["AArch64"],
        },
      ],
      host({
        "/foreign/libcore.so": {
          identity: { machine: 62, bits: 64, byte_order: "little" },
          reason: "bad dynamic table",
        },
        "/cached/libcore.so": elf([]),
      }),
      10,
    );
    expect(closure).toEqual({
      libraries: [{ soname: "libcore.so", path: "/cached/libcore.so" }],
      missing: [],
      unreadable: [],
      truncated: false,
    });
  });
});

describe("libraryClosure unresolved candidates", () => {
  it("does not turn unknown candidate identity into a selected library or search past it", async () => {
    const closure = await libraryClosure(
      app(elf(["libcore.so"], [], ["/unreadable", "/native"])),
      [],
      host({
        "/unreadable/libcore.so": "cannot read header",
        "/native/libcore.so": elf([]),
      }),
      10,
    );
    expect(closure).toEqual({
      libraries: [],
      missing: [],
      unreadable: [
        { path: "/unreadable/libcore.so", reason: "cannot read header" },
      ],
      truncated: false,
    });
  });

  it("refuses an incompatible explicit path without claiming its package was selected", async () => {
    const path = "/foreign/libcore.so";
    const closure = await libraryClosure(
      app(elf([path])),
      [],
      host({ [path]: { ...elf([]), machine: 62 } }),
      10,
    );
    expect(closure).toMatchObject({
      libraries: [],
      missing: [],
      unreadable: [
        { path, reason: expect.stringContaining("incompatible ELF") },
      ],
      truncated: false,
    });
  });

  it("continues to another matching cache candidate after foreign identity", async () => {
    const closure = await libraryClosure(
      app(elf(["libcore.so"])),
      [
        {
          soname: "libcore.so",
          path: "/foreign/libcore.so",
          flags: ["AArch64"],
        },
        { soname: "libcore.so", path: "/valid/libcore.so", flags: ["AArch64"] },
      ],
      host({
        "/foreign/libcore.so": { ...elf([]), machine: 62 },
        "/valid/libcore.so": elf([]),
      }),
      10,
    );
    expect(closure).toMatchObject({
      libraries: [{ soname: "libcore.so", path: "/valid/libcore.so" }],
      missing: [],
    });
  });

  it("keeps an unreadable first cache candidate unresolved", async () => {
    const closure = await libraryClosure(
      app(elf(["libcore.so"])),
      [
        {
          soname: "libcore.so",
          path: "/unknown/libcore.so",
          flags: ["AArch64"],
        },
        { soname: "libcore.so", path: "/valid/libcore.so", flags: ["AArch64"] },
      ],
      host({
        "/unknown/libcore.so": "cannot read header",
        "/valid/libcore.so": elf([]),
      }),
      10,
    );
    expect(closure).toMatchObject({
      libraries: [],
      missing: [],
      unreadable: [
        { path: "/unknown/libcore.so", reason: "cannot read header" },
      ],
    });
  });

  it("does not trust a cache architecture flag over the candidate's own ELF identity", async () => {
    const closure = await libraryClosure(
      app(elf(["libcore.so"])),
      [
        {
          soname: "libcore.so",
          path: "/cached/libcore.so",
          flags: ["AArch64"],
        },
      ],
      host({ "/cached/libcore.so": { ...elf([]), machine: 62 } }),
      10,
    );
    expect(closure).toEqual({
      libraries: [],
      missing: ["libcore.so"],
      unreadable: [],
      truncated: false,
    });
  });
});

describe("libraryClosure search paths", () => {
  it("expands ORIGIN literally while leaving unsupported source tokens unresolved", async () => {
    const closure = await libraryClosure(
      {
        path: "/opt/$build-$&/bin/app",
        dependencies: elf(
          ["liborigin.so", "libunsupported.so"],
          ["$ORIGIN/../lib", "$ORIGIN/$LIB", "$ORIGIN_SUFFIX", "relative"],
        ),
      },
      [],
      host({
        "/opt/$build-$&/lib/liborigin.so": elf([]),
        "/opt/$build-$&/bin/$LIB/libunsupported.so": elf([]),
        "/opt/$build-$&/bin_SUFFIX/libunsupported.so": elf([]),
      }),
      10,
    );
    expect(closure).toEqual({
      libraries: [
        { soname: "liborigin.so", path: "/opt/$build-$&/lib/liborigin.so" },
      ],
      missing: ["libunsupported.so"],
      unreadable: [],
      truncated: false,
    });
  });

  it("normalizes $ORIGIN/.. before telling the app's own folder from system libraries", async () => {
    const closure = await libraryClosure(
      {
        path: "/usr/bin/tool",
        dependencies: elf(["libtool.so.1"], ["$ORIGIN/../lib"]),
      },
      [],
      host({ "/usr/lib/libtool.so.1": elf([]) }),
      10,
    );

    expect(closure.libraries).toEqual([
      { soname: "libtool.so.1", path: "/usr/lib/libtool.so.1" },
    ]);
  });

  it("searches the executable's RPATH for its libraries' own needs unless they have a RUNPATH", async () => {
    const images = {
      "/opt/app/lib/libcore.so": elf(["libhelper.so"]),
      "/opt/app/lib/libhelper.so": elf([]),
    };
    const inherited = await libraryClosure(
      app(elf(["libcore.so"], ["$ORIGIN/../lib"])),
      [],
      host(images),
      10,
    );
    const ownRunpath = await libraryClosure(
      app(elf(["libcore.so"], ["$ORIGIN/../lib"])),
      [],
      host({
        ...images,
        "/opt/app/lib/libcore.so": elf(["libhelper.so"], [], ["/nowhere"]),
      }),
      10,
    );
    const runpathOnly = await libraryClosure(
      app(elf(["libcore.so"], [], ["$ORIGIN/../lib"])),
      [],
      host(images),
      10,
    );

    expect(inherited).toMatchObject({
      libraries: [
        { soname: "libcore.so", path: "/opt/app/lib/libcore.so" },
        { soname: "libhelper.so", path: "/opt/app/lib/libhelper.so" },
      ],
      missing: [],
    });
    expect(ownRunpath.missing).toEqual(["libhelper.so"]);
    expect(runpathOnly.missing).toEqual(["libhelper.so"]);
  });
});

describe("installableLibraryPackages", () => {
  const NOBLE =
    "http://ports.ubuntu.com/ubuntu-ports noble/main arm64 Packages";
  const PPA =
    "https://ppa.launchpadcontent.net/a/b/ubuntu noble/main arm64 Packages";
  const TYPORA = "https://downloads.typora.io/linux ./ Packages";

  it("keeps packages the Ubuntu 24.04 archive or a declared repository offers", () => {
    expect(
      installableLibraryPackages(
        ["libnss3", "libfoo", "typora-helper", "libgone"],
        {
          sources: new Map([
            ["libnss3", [PPA, NOBLE]],
            ["libfoo", [PPA]],
            ["typora-helper", [TYPORA]],
          ]),
          origins: new Map([
            [NOBLE, "Ubuntu"],
            [PPA, "LP-PPA-a-b"],
            [TYPORA, "typora.io"],
          ]),
          declared: new Set([TYPORA]),
        },
      ),
    ).toEqual({
      installable: ["libnss3", "typora-helper"],
      uninstallable: ["libfoo", "libgone"],
      supplied: new Map([["typora-helper", [TYPORA]]]),
    });
  });
});

describe("libraryPackageNames", () => {
  it("drops architecture qualifiers and the application's own package", () => {
    expect(
      libraryPackageNames(
        ["libnss3:arm64", "libc6:arm64", "libnss3:arm64", "typora", "libnspr4"],
        "typora:arm64",
      ),
    ).toEqual(["libc6", "libnspr4", "libnss3"]);
  });
});
