const renameShared = (
  entry: InternalPeripheralEntry,
  names: Readonly<Record<string, string>>,
  manualLabel: string,
): InternalPeripheralEntry => {
  const name = names[entry.name];
  if (name === undefined) {
    throw invariantViolation(
      `${manualLabel} has no name for shared ${entry.name}`,
    );
  }
  return {
    ...entry,
    name,
    description:
      name === entry.name
        ? entry.description
        : `${entry.description}; the ${manualLabel} manual calls this ${name}`,
  };
};

