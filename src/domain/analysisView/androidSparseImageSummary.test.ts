it("summarizes an Android sparse image without inline chunk or crc32 arrays", () => {
  const summary = androidSparseImageSummaryMetadataSchema.parse(
    summaryRootMetadata(sparseMetadata()),
  );
  expect(summary).toMatchObject({
    kind: "android-sparse-image-summary",
    block_size: 4096,
    total_blocks: 1024,
    total_chunks: 3,
    chunk_count: 3,
    crc32_value_count: 0,
    unsparsed_size: 1024 * 4096,
    raw_chunk_count: 1,
    fill_chunk_count: 1,
    dont_care_chunk_count: 1,
    raw_data_bytes: 4096,
    virtual_fill_bytes: 23 * 4096,
    virtual_dont_care_bytes: 1000 * 4096,
  });
});
